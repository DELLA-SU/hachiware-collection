import {readFile,writeFile} from 'node:fs/promises';
const source=new URL('../app/translations-data.tsv',import.meta.url),target=new URL('../app/translations.ts',import.meta.url),rows={};
for(const line of (await readFile(source,'utf8')).split(/\r?\n/)){
 if(!line)continue;
 const fields=line.split('|');if(fields.length!==4||fields.some(value=>!value))throw new Error('Each translation needs Korean, English, Chinese and Japanese: '+line);
 const [ko,en,zh,ja]=fields;if(rows[ko])throw new Error('Duplicate translation: '+ko);rows[ko]={en,zh,ja};
}
await writeFile(target,"// Generated by scripts/build-translations.mjs from translations-data.tsv.\nexport const translations:Record<string,{en:string;zh:string;ja:string}>="+JSON.stringify(rows,null,1)+';\n');
console.log('Built '+Object.keys(rows).length+' translations for English, Chinese and Japanese.');
